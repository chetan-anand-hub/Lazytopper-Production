/** The per-question id field the browser sends in each `questions[]` entry of a series grading request. */
const REQUEST_ID_FIELD = 'questionId';

const HEX64 = /^[0-9a-f]{64}$/;
const ID_MAX = 200;
/** A prefix is `ct-ts1-<topicKey>--`, `ct-ts1p<k>-<topicKey>--` or `fm-ts1-<m|s><n>--`: always ends with the "--" separator. */
const PREFIX_SHAPE = /^(ct|fm)-[a-z0-9]+-[a-z0-9-]+--$/;

/**
 * THE canonical text: Unicode NFC, every whitespace run as one space, trimmed. The manifest generator
 * (src/lib/testSeries/paperManifest.ts canonicalQuestionText) uses the same normalisation (a parity test pins the two). PURE.
 */
function canonicalQuestionText(text) {
  return String(text == null ? '' : text).normalize('NFC').replace(/\s+/g, ' ').trim();
}

/** sha256 (hex) of the canonical text. PURE. */
function canonicalQuestionTextHash(text) {
  return crypto.createHash('sha256').update(canonicalQuestionText(text), 'utf8').digest('hex');
}

const str = (v) => (typeof v === 'string' && v.trim() && v.length <= ID_MAX ? v.trim() : '');

/**
 * Validate a parsed manifest (a top-level array) into a lookup. A paper that is not entirely well-formed is DROPPED (fail
 * closed for that paper): a written id with no hash, a written id outside questionIds, a duplicate key or prefix. PURE.
 * @returns {{ papers: object[], byKey: Map<string, object>, count: number, dropped: number }}
 */
function indexManifest(raw) {
  const list = Array.isArray(raw) ? raw : [];
  const papers = [];
  const byKey = new Map();
  const prefixes = new Set();
  let dropped = 0;
  for (const p of list) {
    const key = str(p && p[F.key]);
    const prefix = str(p && p[F.prefix]);
    const questionIds = Array.isArray(p && p[F.questionIds]) ? p[F.questionIds].map(str) : null;
    const writtenIds = Array.isArray(p && p[F.writtenIds]) ? p[F.writtenIds].map(str) : null;
    const hashes = p && p[F.textHashes] && typeof p[F.textHashes] === 'object' && !Array.isArray(p[F.textHashes]) ? p[F.textHashes] : null;
    const ok =
      key && prefix && PREFIX_SHAPE.test(prefix) && questionIds && writtenIds && hashes && writtenIds.length > 0
      && questionIds.every(Boolean) && writtenIds.every(Boolean)
      && new Set(writtenIds).size === writtenIds.length
      && writtenIds.every((id) => questionIds.includes(id) && Object.prototype.hasOwnProperty.call(hashes, id) && typeof hashes[id] === 'string' && HEX64.test(hashes[id]))
      && !byKey.has(key) && !prefixes.has(prefix);
    if (!ok) {
      dropped += 1;
      continue;
    }
    const paper = Object.freeze({
      key,
      paperCode: str(p[F.paperCode]) || null,
      prefix,
      written: new Map(writtenIds.map((id) => [id, hashes[id]])),
    });
    papers.push(paper);
    byKey.set(key, paper);
    prefixes.add(prefix);
  }
  return { papers, byKey, count: papers.length, dropped };
}

/**
 * Read and index the manifest file. Missing / unreadable / no usable paper -> no papers, and an ERROR is logged.
 * TS-THEMES-1: `file` may be a LIST of files (MANIFEST_FILES), indexed as one manifest. A missing or unreadable file in a list is
 * logged and skipped (the others still load); only when NONE can be read is the manifest empty.
 */
function loadManifest(file = MANIFEST_PATH, logger = console) {
  let out;
  try {
    if (Array.isArray(file)) {
      const all = [];
      let read = 0;
      for (const f of file) {
        try {
          const raw = JSON.parse(fs.readFileSync(f, 'utf8'));
          if (Array.isArray(raw)) all.push(...raw);
          read += 1;
        } catch (e) {
          try {
            logger.error(`[test-series] manifest file unreadable (${f}) - its papers cannot be checked on the pack: ${(e && e.message) || e}`);
          } catch {
            /* logging never fails a boot */
          }
        }
      }
      if (read === 0) throw new Error('no manifest file could be read');
      out = indexManifest(all);
    } else {
      out = indexManifest(JSON.parse(fs.readFileSync(file, 'utf8')));
    }
  } catch (e) {
    out = { papers: [], byKey: new Map(), count: 0, dropped: 0, unreadable: true };
    try {
      logger.error(`[test-series] manifest unreadable (${file}) - NO Test Series paper can be checked on the pack: ${(e && e.message) || e}`);
    } catch {
      /* logging never fails a boot */
    }
    return out;
  }
  try {
    if (out.dropped > 0) logger.error(`[test-series] manifest: ${out.dropped} paper(s) malformed and NOT admitted`);
    if (out.count === 0) logger.error('[test-series] manifest loaded 0 papers - NO Test Series paper can be checked on the pack');
  } catch {
    /* logging never fails a boot */
  }
  return out;
}

/**
 * The manifest paper this request names (its worksheetId starts with the paper's prefix), or null. PURE.
 * `opts.moreDisabled` (TS_MORE_DISABLED): the papers TS-MORE-1 added are skipped, as if the manifest did not list them.
 * Every prefix ends in "--" and no prefix is a prefix of another (a guard test pins it), so at most one paper can match.
 */
function seriesPaperOf(body, manifest, opts) {
  if (!manifest || !body || typeof body !== 'object') return null;
  const id = typeof body.worksheetId === 'string' ? body.worksheetId.trim() : '';
  if (!id || id.length > ID_MAX) return null;
  const skipMore = !!(opts && opts.moreDisabled);
  const skipFocus = !!(opts && opts.focusDisabled);
  for (const p of manifest.papers) {
    if (skipMore && isMorePaper(p)) continue;
    if (skipFocus && isFocusPaper(p)) continue;
    if (id.startsWith(p.prefix) && id.length > p.prefix.length) return p;
  }
  return null;
}

/**
 * Does EVERY submitted question belong to `paper`'s written list with its canonical text? PURE.
 * Checks the RAW `questions` array - every entry, not only the ones the grader later keeps.
 * @returns {{ ok: true } | { ok: false, reason: string }}
 */
function verifySubmission(body, paper) {
  const qs = body && Array.isArray(body.questions) ? body.questions : null;
  if (!qs || qs.length === 0) return { ok: false, reason: 'no_questions' };
  if (qs.length > paper.written.size) return { ok: false, reason: 'too_many_questions' };
  const seen = new Set();
  for (const q of qs) {
    const id = str(q && q[REQUEST_ID_FIELD]);
    if (!id) return { ok: false, reason: 'missing_question_id' };
    if (!paper.written.has(id)) return { ok: false, reason: 'not_a_written_question' };
    if (seen.has(id)) return { ok: false, reason: 'duplicate_question' };
    seen.add(id);
    if (canonicalQuestionTextHash(q && q.questionText) !== paper.written.get(id)) return { ok: false, reason: 'question_text_mismatch' };
  }
  return { ok: true };
}

