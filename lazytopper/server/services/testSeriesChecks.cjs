const docId = (v) => (typeof v === 'string' && v.trim() && !v.includes('/') ? v.trim() : '');
const mapOf = (data, field) => (data && data[field] && typeof data[field] === 'object' && !Array.isArray(data[field]) ? data[field] : {});

/** The committed count for one paper (anything unusable reads as 0; a large number stays large). PURE. */
function usedOn(data, paperKey) {
  const n = mapOf(data, CHECKS_FIELD)[paperKey];
  return typeof n === 'number' && Number.isFinite(n) && n > 0 ? Math.floor(n) : 0;
}

/** Has this paper's one free re-check been given? PURE. */
function freeRecheckSpent(data, paperKey) {
  return Object.prototype.hasOwnProperty.call(mapOf(data, FREE_FIELD), paperKey);
}

/** The holds still counting at `nowMs` (younger than HOLD_TTL_MS). PURE. */
function liveHolds(data, nowMs) {
  const out = {};
  for (const [id, h] of Object.entries(mapOf(data, HOLDS_FIELD))) {
    const at = h && typeof h === 'object' ? Number(h.atMs) : NaN;
    if (h && typeof h.paper === 'string' && Number.isFinite(at) && nowMs - at < HOLD_TTL_MS && at - nowMs < HOLD_TTL_MS) out[id] = { paper: h.paper, atMs: at };
  }
  return out;
}

function heldOn(holds, paperKey) {
  return Object.values(holds).filter((h) => h.paper === paperKey).length;
}

/** True when this stored pack document is a live Test Series Pack at `nowMs`. PURE. */
function isLivePack(pack, nowMs) {
  return !!pack && pack.sku === TEST_SERIES_SKU && pack.packId === TEST_SERIES_PACK_ID
    && Number.isFinite(nowMs) && nowMs <= TEST_SERIES_ENDS_MS;
}

/**
 * @param {{ adminFirestore: object|null, telemetry?: object|null, now?: () => number, manifest?: object,
 *           readBody?: (req) => Promise<object>, newHoldId?: () => string, logger?: object }} deps
 */
function createTestSeriesChecks(deps = {}) {
  const { adminFirestore = null, telemetry = null, now = () => Date.now(), readBody = null, env = process.env } = deps;
  const newHoldId = typeof deps.newHoldId === 'function' ? deps.newHoldId : () => crypto.randomUUID().replace(/-/g, '');
  const manifest = deps.manifest || loadManifest(MANIFEST_FILES, deps.logger || console);
  const emit = (e) => {
    try {
      if (telemetry && typeof telemetry.increment === 'function') telemetry.increment(e);
    } catch {
      /* telemetry never blocks */
    }
  };
  const userRefOf = (uid) => adminFirestore.collection(ENTITLEMENTS_COLLECTION).doc(uid);
  const packRefOf = (uid) => userRefOf(uid).collection(PACK_SEGMENTS.packs).doc(TEST_SERIES_PACK_ID);
  const usable = () => !!adminFirestore && typeof adminFirestore.collection === 'function';
  const transacts = () => !!adminFirestore && typeof adminFirestore.runTransaction === 'function';

  /** Does the uid own a live Test Series Pack? true / false, or null when it cannot be read. */
  async function ownsActive(uid) {
    const id = docId(uid);
    if (!id || !usable()) return null;
    try {
      const snap = await packRefOf(id).get();
      return isLivePack(snap && snap.exists ? snap.data() || {} : null, now());
    } catch {
      emit('test_series.read_failed');
      return null;
    }
  }

  /**
   * The owner's view for GET /api/packs/mine: { owned, active, validUntilMs, checksPerPaper, used: { <paper key>: n } } (only
   * papers with a committed check or a live hold), or null when not owned / unreadable.
   */
  async function status(uid) {
    const id = docId(uid);
    if (!id || !usable()) return null;
    try {
      const [packSnap, userSnap] = await Promise.all([packRefOf(id).get(), userRefOf(id).get()]);
      const pack = packSnap && packSnap.exists ? packSnap.data() || {} : null;
      if (!pack || pack.sku !== TEST_SERIES_SKU) return null;
      const data = userSnap && userSnap.exists ? userSnap.data() || {} : {};
      const nowMs = now();
      const holds = liveHolds(data, nowMs);
      const used = {};
      const freeRecheck = {};
      for (const p of manifest.papers) {
        const n = usedOn(data, p.key) + heldOn(holds, p.key);
        if (n > 0) used[p.key] = Math.min(n, CHECKS_PER_PAPER);
        // TS-RECHECK-1: the paper's latest check was NOT counted (its free re-check) and no check has been made since.
        if (freeRecheckSpent(data, p.key) && mapOf(data, FREE_FIELD)[p.key] === usedOn(data, p.key) && heldOn(holds, p.key) === 0) freeRecheck[p.key] = true;
      }
      return {
        owned: true, active: isLivePack(pack, nowMs), validUntilMs: TEST_SERIES_ENDS_MS, checksPerPaper: CHECKS_PER_PAPER, used,
        ...(Object.keys(freeRecheck).length > 0 ? { freeRecheck } : {}),
      };
    } catch {
      emit('test_series.read_failed');
      return null;
    }
  }

  /**
   * ONE transaction: ownership + this paper's committed count + its live holds, and a new hold when a check is left. Expired
   * holds are dropped in the same write. Never throws.
   * -> { kind: 'held', holdId, used, left } | 'not_owner' | 'expired' | 'exhausted' | 'unavailable'
   */
  async function hold(uid, paper) {
    const id = docId(uid);
    if (!id || !transacts()) return { kind: 'unavailable' };
    const nowMs = now();
    const holdId = newHoldId();
    try {
      return await adminFirestore.runTransaction(async (tx) => {
        const userRef = userRefOf(id);
        // Every read before any write (Firestore's transaction contract).
        const packSnap = await tx.get(packRefOf(id));
        const userSnap = await tx.get(userRef);
        const pack = packSnap && packSnap.exists ? packSnap.data() || {} : null;
        if (!pack || pack.sku !== TEST_SERIES_SKU) return { kind: 'not_owner' };
        if (!isLivePack(pack, nowMs)) return { kind: 'expired' };
        const data = userSnap && userSnap.exists ? userSnap.data() || {} : {};
        const holds = liveHolds(data, nowMs);
        const taken = usedOn(data, paper.key) + heldOn(holds, paper.key);
        if (taken >= CHECKS_PER_PAPER) return { kind: 'exhausted', used: CHECKS_PER_PAPER, left: 0 };
        holds[holdId] = { paper: paper.key, atMs: nowMs };
        tx.set(userRef, { [HOLDS_FIELD]: holds, updatedAt: new Date(nowMs) }, { merge: true });
        return { kind: 'held', holdId, used: taken + 1, left: CHECKS_PER_PAPER - taken - 1 };
      });
    } catch {
      emit('test_series.hold_failed');
      return { kind: 'unavailable' };
    }
  }

  /**
   * Settle ONE hold: `keep` -> the check is spent (committed count + 1); otherwise it is given back. The hold is removed either
   * way. A commit whose hold already expired still counts the delivered grade. Never throws; never below 0.
   */
  async function settleHold(uid, paperKey, holdId, keep, free = false) {
    const id = docId(uid);
    if (!id || !transacts()) return false;
    try {
      const done = await adminFirestore.runTransaction(async (tx) => {
        const userRef = userRefOf(id);
        const snap = await tx.get(userRef);
        const data = snap && snap.exists ? snap.data() || {} : {};
        const nowMs = now();
        const holds = liveHolds(data, nowMs);
        const had = Object.prototype.hasOwnProperty.call(holds, holdId);
        delete holds[holdId];
        const write = { [HOLDS_FIELD]: holds, updatedAt: new Date(nowMs) };
        // TS-RECHECK-1: a kept check whose sheet was mostly unreadable is given back ONCE per paper. Decided here, in the same
        // transaction that reads the counter, so two parallel settles cannot both take the free re-check. Only for a hold that is
        // still live: a hold that expired before settle is counted exactly as before this lane (no refund for an expired hold).
        if (keep && free && had && !freeRecheckSpent(data, paperKey)) {
          write[FREE_FIELD] = { ...mapOf(data, FREE_FIELD), [paperKey]: usedOn(data, paperKey) };
          tx.set(userRef, write, { merge: true });
          return 'free_recheck';
        }
        if (keep) write[CHECKS_FIELD] = { ...mapOf(data, CHECKS_FIELD), [paperKey]: usedOn(data, paperKey) + 1 };
        tx.set(userRef, write, { merge: true });
        return keep ? 'committed' : had ? 'released' : 'release_noop';
      });
      emit(`test_series.check_${done}`);
      return true;
    } catch {
      emit('test_series.settle_failed');
      return false;
    }
  }

  /**
   * Settle the hold EXACTLY ONCE, the way idempotency settles (fairUse.cjs attach): when the handler calls res.end - kept for
   * a 2xx that graded at least one question, released otherwise - or released when the connection closes before the handler
   * ever answered. Never on a close that follows an end (that was the abort-then-replay refund hole).
   */
  function settleOnEnd(res, uid, paper, holdId, env = process.env) {
    if (!res) return;
    let settled = false;
    const settle = (keep, free = false) => {
      if (settled) return;
      settled = true;
      void Promise.resolve(settleHold(uid, paper.key, holdId, keep, free)).catch(() => {});
    };
    if (typeof res.end === 'function') {
      const end = res.end;
      res.end = function testSeriesEnd() {
        if (!settled) {
          const status = Number(res.statusCode) || 0;
          if (status === 202) {
            // TS-PACK-JOBFIX: a background job took the grade - the hold rides its `deferred` and settles when the job ends.
            settled = true;
            emit('test_series.check_job');
          } else {
            const charged = chargeableCountOf(res);
            const keep = status >= 200 && status < 300 && charged !== undefined && charged > 0;
            settle(keep, keep && !testSeriesRecheckDisabled(env) && mostlyUnreadable(unreadableSummaryOf(res)));
          }
        }
        return end.apply(this, arguments);
      };
    }
    if (typeof res.once === 'function') {
      res.once('close', () => settle(false)); // a no-op once res.end has settled it
    }
  }

  /** The request body, read ONCE (the handler later gets the same parse). null when it cannot be parsed. */
  async function bodyOf(req) {
    if (typeof readBody !== 'function') return null;
    try {
      const b = await readBody(req);
      return b && typeof b === 'object' ? b : null;
    } catch {
      return null;
    }
  }

  /**
   * The decision for a grade-worksheet request from a NON-Premium caller. Never throws.
   *   { kind: 'not_series' }                          not a Test Series paper: the caller's ordinary rules apply
   *   { kind: 'admitted', paperKey, used, left }      graded on the pack; the hold settles when the response ends
   *   { kind: 'refused', reason, ... }                a series paper this caller may not have checked on the pack
   */
  async function decide(req, res, uid) {
    if (manifest.count === 0) return { kind: 'not_series' };
    const body = await bodyOf(req);
    const paper = seriesPaperOf(body, manifest, paperOpts(env));
    if (!paper) return { kind: 'not_series' };
    emit('test_series.series_request');
    const verdict = verifySubmission(body, paper);
    if (!verdict.ok) {
      emit(`test_series.mismatch.${verdict.reason}`);
      return { kind: 'refused', reason: 'series_paper_mismatch', detail: verdict.reason, paperKey: paper.key };
    }
    const r = await hold(uid, paper);
    if (r.kind !== 'held') {
      emit(`test_series.refused.${r.kind}`);
      return { kind: 'refused', reason: r.kind, paperKey: paper.key, ...(r.kind === 'exhausted' ? { used: r.used, left: 0 } : {}) };
    }
    // TS-PACK-JOBFIX: graded like every other paper (a background job when the browser asks for one). The hold goes with the
    // response so the grade route can put it into the job's `deferred`; a synchronous answer settles it from res.end.
    setTestSeriesDeferred(res, { uid: docId(uid), paper: paper.key, holdId: r.holdId });
    settleOnEnd(res, uid, paper, r.holdId, env);
    emit('test_series.check_held');
    return { kind: 'admitted', paperKey: paper.key, used: r.used, left: r.left };
  }

  /**
   * TS-PACK-JOBFIX (review P0 #1) - is this a VERIFIED, unexpired Test Series Pack owner on one of the manifest's series papers of
   * this kind? `worksheetId` must start with a paper's prefix and the kind must match the paper (ct- = chapter-test, fm- =
   * full-mock). LIMITS-1 then neither meters nor locks it: the pack's own 2-per-paper rule is the only cap. Never throws; any
   * doubt (no manifest, unreadable pack) is false - the ordinary limits apply.
   */
  async function ownerSeriesPaper(uid, kind, worksheetId) {
    try {
      // The kill switch turns the exemption off too: with TS_CHECKS_DISABLED every paper is metered exactly as before.
      if (testSeriesChecksDisabled(env) || manifest.count === 0) return false;
      const paper = seriesPaperOf({ worksheetId }, manifest, paperOpts(env));
      if (!paper) return false;
      const paperKind = paper.prefix.startsWith('ct-') ? 'chapter-test' : paper.prefix.startsWith('fm-') ? 'full-mock' : '';
      if (kind !== paperKind) return false;
      return (await ownsActive(uid)) === true;
    } catch {
      return false;
    }
  }

  /**
   * TS-PACK-JOBFIX (review P0 #1) - the grading gate's question: is this grade-worksheet request a Test Series Pack owner's grade of
   * a series paper with exactly that paper's written questions (the SAME checks admission makes)? Reads the body once (the
   * handler gets the same parse). Never throws; false on any doubt.
   */
  async function ownerSeriesGrade(req, uid) {
    try {
      if (testSeriesChecksDisabled(env) || manifest.count === 0) return false;
      const body = await bodyOf(req);
      const paper = seriesPaperOf(body, manifest, paperOpts(env));
      if (!paper || !verifySubmission(body, paper).ok) return false;
      return (await ownsActive(uid)) === true;
    } catch {
      return false;
    }
  }

  /**
   * TS-PACK-JOBFIX - a background grading job ended (grading/jobs.cjs commitDeferred, called ONCE by the claim winner): keep the
   * hold when at least one question was graded, release it otherwise. A deferred without a series hold does nothing. Never throws.
   */
  function settleDeferred(deferred, graded, detail) {
    try {
      const ref = deferred && typeof deferred === 'object' ? deferred.testSeries : null;
      if (!ref || typeof ref.uid !== 'string' || typeof ref.paper !== 'string' || typeof ref.holdId !== 'string') return;
      // A replayed settle of the SAME deferred is a no-op (the job claim winner settles once; this guards a replay in-process).
      if (SETTLED_REFS.has(ref)) return;
      SETTLED_REFS.add(ref);
      const keep = Math.floor(Number(graded) || 0) > 0;
      const free = keep && !testSeriesRecheckDisabled(env) && mostlyUnreadable(detail);
      void Promise.resolve(settleHold(ref.uid, ref.paper, ref.holdId, keep, free)).catch(() => {});
    } catch {
      emit('test_series.settle_failed');
    }
  }

  return { decide, ownsActive, ownerSeriesPaper, ownerSeriesGrade, status, hold, settleHold, settleDeferred, manifest };
}

