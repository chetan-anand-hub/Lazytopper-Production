/**
 * NoteRichText — renders one note-spec text field.
 *
 * Spec text fields (see notes/specs/*.json) mix three ingredients:
 *   - `$…$` inline LaTeX (KaTeX — the prototype's auto-render contract),
 *   - light inline HTML (`<b>`, `<i>`) and entities (`&amp;`) carried over
 *     from the locked note prototypes,
 *   - plain prose.
 *
 * Trust boundary: spec JSON is repo-committed content that passes
 * `notes/validate_spec.py` and owner review before merge — the same trust
 * level as source code, never user input. KaTeX runs with trust:false.
 *
 * This is intentionally NOT MathText: MathText speaks the question bank's
 * `\(...\)` dialect with bare-pattern heuristics; note-specs are authored
 * against the `$…$` prototype contract and must not be heuristically mangled.
 *
 * ★ PERF-1 (F1) — NO KATEX ON THE PAGE.
 * The HTML of every spec formula is PRECOMPUTED at build time (`noteMathStore`, generated by
 * `scripts/genNoteMath.ts` with the same options and loaded with the chapter's spec), so this
 * file no longer imports katex and a note page makes no `renderToString` call. What is rendered
 * is byte-identical to the old output. A formula missing from the map (a stale map, or text that
 * did not come from a spec) is rendered through a lazily imported katex instead.
 *
 * (Deferring off-screen formulas to the viewport was tried and dropped: it removed two thirds of
 * the DOM but moved Lighthouse TBT by nothing measurable, and the SEO capture needs every
 * formula in the DOM — see the PERF-1 report on #973.)
 */

import { useEffect, useMemo, useState } from "react";
import "katex/dist/katex.min.css";
import { NOTE_KATEX_OPTIONS, NOTE_MATH_RE, noteLatexKey } from "./noteMathCore";
import { lookupNoteMath } from "./noteMathStore";

interface NoteRichTextProps {
  text: string;
  className?: string;
}

type Segment = { type: "html"; html: string } | { type: "math"; latex: string; raw: string };

function segment(text: string): Segment[] {
  const segments: Segment[] = [];
  let last = 0;
  for (const match of text.matchAll(NOTE_MATH_RE)) {
    const index = match.index ?? 0;
    if (index > last) {
      segments.push({ type: "html", html: text.slice(last, index) });
    }
    segments.push({ type: "math", latex: noteLatexKey(match[1]), raw: match[0] });
    last = index + match[0].length;
  }
  if (last < text.length) {
    segments.push({ type: "html", html: text.slice(last) });
  }
  return segments;
}

/** A formula the precomputed map does not hold: render it through a lazily imported katex. */
function LateMath({ latex, raw }: { latex: string; raw: string }) {
  const [done, setDone] = useState<{ latex: string; html: string | null } | null>(null);
  useEffect(() => {
    let live = true;
    void import("katex").then(
      (mod) => {
        let html: string | null = null;
        try {
          html = mod.default.renderToString(latex, { ...NOTE_KATEX_OPTIONS });
        } catch {
          html = null;
        }
        if (live) setDone({ latex, html });
      },
      () => {
        if (live) setDone({ latex, html: null });
      },
    );
    return () => {
      live = false;
    };
  }, [latex]);
  if (done?.latex !== latex) return null;
  // KaTeX refused → show the raw LaTeX rather than dropping content.
  return <span dangerouslySetInnerHTML={{ __html: done.html ?? raw }} />;
}

export function NoteRichText({ text, className }: NoteRichTextProps) {
  const segments = useMemo(() => segment(text ?? ""), [text]);
  return (
    <span className={className}>
      {segments.map((seg, i) => {
        if (seg.type === "html") return <span key={i} dangerouslySetInnerHTML={{ __html: seg.html }} />;
        const known = lookupNoteMath(seg.latex);
        return known !== undefined ? (
          <span key={i} dangerouslySetInnerHTML={{ __html: known }} />
        ) : (
          <LateMath key={i} latex={seg.latex} raw={seg.raw} />
        );
      })}
    </span>
  );
}

export default NoteRichText;
