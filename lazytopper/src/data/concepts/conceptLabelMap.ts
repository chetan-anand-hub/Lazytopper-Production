function buildExamTrendsConcepts(): Record<ChapterSlug, readonly string[]> {
  const out = {} as Record<ChapterSlug, readonly string[]>;
  for (const [slug, topic] of Object.entries(MATH_TOPIC_BY_SLUG)) {
    out[slug as ChapterSlug] = Object.freeze(
      Object.keys(class10MathTopicTrends.topics[topic].conceptWeightage),
    );
  }
  for (const [slug, topic] of Object.entries(SCIENCE_TOPIC_BY_SLUG)) {
    out[slug as ChapterSlug] = Object.freeze(
      class10ScienceTopicTrends.topics[topic].concepts.map((c) => c.name),
    );
  }
  return out;
}

